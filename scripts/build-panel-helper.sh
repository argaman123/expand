#!/usr/bin/env bash
# Builds sidescreen-panel, the menu-bar panel helper (macOS only).
# Output: target/sidescreen-panel. The Tauri bundle copies it into Sidescreen.app/Contents/MacOS.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
mkdir -p "$ROOT/target"

# The menu-bar icon (a template image, 1x and 2x) and the header's app icon, embedded in the
# binary. scripts/render-icons.sh makes them.
ICONS="$ROOT/target/panel-icons.swift"
{
  echo "// Generated by scripts/build-panel-helper.sh. Do not edit."
  echo "let trayIconPNG = \"$(base64 < "$ROOT/app/src-tauri/icons/tray-template.png" | tr -d '\n')\""
  echo "let trayIcon2xPNG = \"$(base64 < "$ROOT/app/src-tauri/icons/tray-template@2x.png" | tr -d '\n')\""
  echo "let appIconPNG = \"$(base64 < "$ROOT/app/src-tauri/icons/64x64.png" | tr -d '\n')\""
} > "$ICONS"

# macOS 14 is the app's minimum (tauri.conf.json); the target makes the compiler check it.
xcrun swiftc -O -swift-version 5 -parse-as-library \
  -target "$(uname -m)-apple-macos14.0" \
  -file-prefix-map "$ROOT=." \
  "$ROOT"/mac/panel/*.swift "$ICONS" \
  -o "$ROOT/target/sidescreen-panel"
echo "built: $ROOT/target/sidescreen-panel"
